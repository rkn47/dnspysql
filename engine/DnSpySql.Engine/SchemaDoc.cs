using System.Text;

using DnSpySql.Tables;

namespace DnSpySql;

/// <summary>Generates docs/SCHEMA.md from the live catalog (so the reference never drifts from the code).</summary>
public static class SchemaDoc
{
    public static string Markdown(Session s)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# DnSpySql schema reference");
        sb.AppendLine();
        sb.AppendLine($"Generated by `dnspysql --schema-md` (v{Session.ToolVersion}). {s.Db.Tables.Count} tables, {Views.All.Length} views, {s.Db.Functions.Select(f => f.Name).Distinct().Count()} functions.");
        sb.AppendLine();
        sb.AppendLine("Legend: **w** writable (UPDATE), pushdown `eq`/`unique`/`range` = filter answered by the engine, **req** = the table needs an equality filter on one of these columns, *arg* = hidden input column (table-valued-function argument).");
        sb.AppendLine();
        foreach (var domain in s.Db.Tables.GroupBy(t => t.Domain).OrderBy(g => DomainOrder(g.Key)))
        {
            sb.AppendLine($"## {domain.Key}");
            sb.AppendLine();
            foreach (var t in domain)
            {
                var ops = new List<string>();
                if (t.CanUpdate) ops.Add("UPDATE");
                if (t.CanInsert) ops.Add("INSERT");
                if (t.CanDelete) ops.Add("DELETE");
                sb.AppendLine($"### `{t.Name}`{(ops.Count > 0 ? " — " + string.Join(", ", ops) : "")}");
                sb.AppendLine();
                sb.AppendLine(t.Doc);
                if (t.Columns.Any(c => c.Required)) sb.AppendLine().AppendLine($"Required filter: `{t.RequiredHint()}`");
                sb.AppendLine();
                sb.AppendLine("| column | type | flags | description |");
                sb.AppendLine("|---|---|---|---|");
                foreach (var c in t.Columns)
                {
                    var flags = new List<string>();
                    if (c.Writable) flags.Add("**w**");
                    if (c.Pushdown != DnSpySql.Sql.Pushdown.None) flags.Add($"`{c.Pushdown.ToString().ToLowerInvariant()}`");
                    if (c.Required) flags.Add("**req**");
                    if (c.IsArgument) flags.Add("*arg*");
                    sb.AppendLine($"| {c.Name} | {c.Type.ToString().ToUpperInvariant()} | {string.Join(" ", flags)} | {(c.Doc ?? "").Replace("|", "\\|")} |");
                }
                sb.AppendLine();
            }
        }
        sb.AppendLine("## views");
        sb.AppendLine();
        foreach (var (name, doc, sql) in Views.All)
        {
            sb.AppendLine($"### `{name}`");
            sb.AppendLine();
            sb.AppendLine(doc);
            sb.AppendLine();
            sb.AppendLine("```sql");
            sb.AppendLine(string.Join("\n", sql.Split('\n').Select(l => l.Trim())));
            sb.AppendLine("```");
            sb.AppendLine();
        }
        sb.AppendLine("## functions");
        sb.AppendLine();
        foreach (var g in s.Db.Functions.GroupBy(f => f.Domain).OrderBy(g => DomainOrder(g.Key)))
        {
            sb.AppendLine($"### {g.Key}");
            sb.AppendLine();
            sb.AppendLine("| signature | writes | description |");
            sb.AppendLine("|---|---|---|");
            foreach (var f in g.GroupBy(f => f.Name).Select(x => x.First()).OrderBy(f => f.Name))
                // a table cell ends at a bare "|", inside a code span too (GitHub drops the backslash there)
                sb.AppendLine($"| `{f.Signature.Replace("|", "\\|")}` | {(f.Mutates ? "yes" : "")} | {f.Doc.Replace("|", "\\|")} |");
            sb.AppendLine();
        }
        return sb.ToString();
    }

    static int DomainOrder(string d) => Array.IndexOf(new[]
    {
        "meta", "core", "session", "metadata", "code", "xrefs", "decompiler", "search", "resources", "pe", "pdb", "annotations",
        "edit", "compile", "breakpoints", "debugger",
    }, d) is var i && i >= 0 ? i : 99;
}
